"""Application contracts. Repositories share the scope of one unit of work."""
from __future__ import annotations
from typing import ContextManager, Protocol
from .models import (
    AtomicSkill, Evaluation, EvidenceRecord, JsonObject,
    PracticeRecord, PracticeSession, SessionHistory, Skill,
)
from .catalog import Role, KnowledgeConcept
from .commands import SkillPatch
from .projects import LearningProject, ProjectObservation


class JSONClient(Protocol):
    def generate_json(self, task: str, payload: JsonObject) -> JsonObject: ...


class Skills(Protocol):
    def catalog_roles(self) -> list[Role]: ...
    def catalog_knowledge(self) -> list[KnowledgeConcept]: ...
    def get(self, skill_id: str, include_deleted: bool = False) -> Skill: ...
    def list(self, enabled_only: bool = False) -> list[Skill]: ...
    def name_exists(self, name: str) -> bool: ...
    def add(self, skill: Skill) -> Skill: ...
    def update(self, skill_id: str, changes: SkillPatch) -> Skill: ...
    def delete(self, skill_id: str, stamp: str) -> None: ...
    def atom(self, atom_id: str) -> AtomicSkill: ...
    def atoms(self) -> list[AtomicSkill]: ...
    def add_atom(self, atom: AtomicSkill) -> AtomicSkill: ...


class Practices(Protocol):
    def get(self, session_id: str, user_id: str) -> PracticeSession: ...
    def add(self, session: PracticeSession) -> None: ...
    def complete(self, session_id: str, answer: str, result: Evaluation, stamp: str) -> None: ...
    def latest_answer(self, session_id: str) -> str | None: ...
    def record_id(self, session_id: str) -> str | None: ...
    def add_record(self, record: PracticeRecord) -> None: ...
    def records(self, user_id: str) -> list[PracticeRecord]: ...
    def delete_record(self, record_id: str, user_id: str, stamp: str) -> None: ...
    def history(self, user_id: str, skill_id: str | None = None) -> list[SessionHistory]: ...


class Progress(Protocol):
    def add_evidence(self, user_id: str, evidence: EvidenceRecord) -> None: ...
    def evidence(self, user_id: str) -> list[EvidenceRecord]: ...


class Users(Protocol):
    def ensure(self, user_id: str) -> None: ...


class Projects(Protocol):
    def get(self, project_id: str, user_id: str) -> LearningProject: ...
    def list(self, user_id: str) -> list[LearningProject]: ...
    def created(self, user_id: str, request_id: str, values) -> LearningProject | None: ...
    def add(self, project: LearningProject, request_id: str, values) -> None: ...
    def save(self, project: LearningProject, expected: int) -> None: ...
    def claim(self, project: LearningProject, request_id: str, values) -> bool: ...
    def done(self, project_id: str, request_id: str) -> None: ...
    def release(self, project_id: str, request_id: str) -> None: ...
    def busy(self, project_id: str) -> bool: ...
    def add_observation(self, observation: ProjectObservation) -> None: ...
    def observations(self, user_id: str) -> list[ProjectObservation]: ...
class Diagnoses(Protocol):
    def get(self, session_id: str, user_id: str) -> JsonObject | None: ...
    def add(self, session_id: str, user_id: str, payload: JsonObject, stamp: str) -> None: ...


class UnitOfWork(Protocol):
    @property
    def projects(self) -> Projects: ...
    @property
    def skills(self) -> Skills: ...
    @property
    def practices(self) -> Practices: ...
    @property
    def progress(self) -> Progress: ...
    @property
    def users(self) -> Users: ...
    @property
    def diagnoses(self) -> Diagnoses: ...


class UnitOfWorkFactory(Protocol):
    def read(self) -> ContextManager[UnitOfWork]: ...
    def write(self) -> ContextManager[UnitOfWork]: ...
